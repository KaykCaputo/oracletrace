"""GitHub-flavored Markdown reporter — drop straight into a PR comment,
CI log, or $GITHUB_STEP_SUMMARY.
"""

from datetime import datetime
from typing import List, Optional

from ..tracer import TracerData
from ..compare import ComparisonData, REGRESSION, IMPROVEMENT


def _md_escape(text: str) -> str:
    # keep names from breaking out of table cells / inline code
    return text.replace("|", "\\|").replace("`", "\\`")


def render_markdown(
    data: TracerData,
    comparison: Optional[ComparisonData] = None,
    top: Optional[int] = None,
) -> str:
    meta = data.metadata
    parts: List[str] = []

    parts.append("## ⚡ OracleTrace Performance Report\n")
    parts.append(
        f"**Total time:** {meta.total_execution_time:.4f}s &nbsp;|&nbsp; "
        f"**Functions:** {meta.total_functions} &nbsp;|&nbsp; "
        f"**Generated:** {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n"
    )

    if comparison is not None:
        parts.append("### Comparison vs. baseline\n")
        changed = [
            d for d in comparison.deltas
            if d.status in (REGRESSION, IMPROVEMENT)
            and d.old_time is not None and d.new_time is not None
        ]
        if changed:
            parts.append("| Function | Baseline | Current | Change |")
            parts.append("|---|---:|---:|---:|")
            for d in sorted(changed, key=lambda d: d.percent or 0, reverse=True):
                icon = "🔴" if d.status == REGRESSION else "🟢"
                parts.append(
                    f"| `{_md_escape(d.name)}` | {d.old_time:.4f}s | {d.new_time:.4f}s "
                    f"| {icon} {d.percent:+.1f}% |"
                )
            parts.append("")
        else:
            parts.append("No functions changed beyond the threshold.\n")

        if comparison.new_functions:
            names = ", ".join(f"`{_md_escape(n)}`" for n in comparison.new_functions)
            parts.append(f"**New:** {names}\n")
        if comparison.removed_functions:
            names = ", ".join(f"`{_md_escape(n)}`" for n in comparison.removed_functions)
            parts.append(f"**Removed:** {names}\n")

        if comparison.regressions:
            parts.append(
                f"> 🚨 **{len(comparison.regressions)} regression(s)** above "
                f"{comparison.threshold:.1f}% threshold\n"
            )
        else:
            parts.append(
                f"> ✅ No regressions above {comparison.threshold:.1f}% threshold\n"
            )

    parts.append("### Top functions by total time\n")
    parts.append("| Function | Total Time (s) | Calls | Avg (ms) |")
    parts.append("|---|---:|---:|---:|")
    for fn in sorted(data.functions, key=lambda f: f.total_time, reverse=True)[:top]:
        parts.append(
            f"| `{_md_escape(fn.name)}` | {fn.total_time:.4f} "
            f"| {fn.call_count} | {fn.avg_time * 1000:.3f} |"
        )
    parts.append("")

    parts.append("*Generated by [OracleTrace](https://github.com/KaykCaputo/oracletrace)*")
    return "\n".join(parts) + "\n"


def generate_markdown_report(
    data: TracerData,
    output_path: str,
    comparison: Optional[ComparisonData] = None,
    top: Optional[int] = None,
) -> None:
    content = render_markdown(data, comparison=comparison, top=top)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(content)
